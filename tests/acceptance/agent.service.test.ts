/**
 * Spec: Feature as HTTP service; patient list and health for the UI.
 * Feature: Agent HTTP service
 */
import { afterEach, describe, expect, it } from "vitest";
import { resolve } from "node:path";
import { configFromEnv } from "../../apps/agent/src/config.js";
import { TriageResponseSchema } from "../../apps/agent/src/contract.js";
import { startAgentServer } from "../../apps/agent/src/server.js";

const dataDir = resolve(process.cwd(), "take_home_starter");

describe("Feature: Agent HTTP service", () => {
  let close: (() => Promise<void>) | undefined;

  afterEach(async () => {
    if (close) {
      await close();
      close = undefined;
    }
  });

  it("Scenario: Valid request returns the triage JSON with routing metadata", async () => {
    const config = configFromEnv({
      LLM_PROVIDER: "stub",
      PORT: "0",
      DATA_DIR: dataDir,
    });
    const server = await startAgentServer(config);
    close = server.close;

    const res = await fetch(`${server.baseUrl}/triage`, {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({
        requestId: "r-1",
        question: "When can I go back to work?",
        summaryIds: ["strep_01"],
      }),
    });
    expect(res.status).toBe(200);
    const body = (await res.json()) as {
      requestId: string;
      instanceId: string;
      durationMs: number;
      result: unknown;
    };
    expect(body.requestId).toBe("r-1");
    expect(body.instanceId).toBeTruthy();
    expect(body.durationMs).toBeGreaterThanOrEqual(0);
    expect(TriageResponseSchema.safeParse(body.result).success).toBe(true);
  });

  it("Scenario: Missing requestId is generated by the agent", async () => {
    const config = configFromEnv({
      LLM_PROVIDER: "stub",
      PORT: "0",
      DATA_DIR: dataDir,
    });
    const server = await startAgentServer(config);
    close = server.close;

    const res = await fetch(`${server.baseUrl}/triage`, {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({
        question: "When can I go back to work?",
        summaryIds: ["strep_01"],
      }),
    });
    const body = (await res.json()) as { requestId: string };
    expect(body.requestId).toBeTruthy();
  });

  it("Scenario: Missing question is a 400", async () => {
    const config = configFromEnv({
      LLM_PROVIDER: "stub",
      PORT: "0",
      DATA_DIR: dataDir,
    });
    const server = await startAgentServer(config);
    close = server.close;

    const res = await fetch(`${server.baseUrl}/triage`, {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({ summaryIds: ["strep_01"] }),
    });
    expect(res.status).toBe(400);
    const body = (await res.json()) as { error: string };
    expect(body.error).toMatch(/question/i);
  });

  it("Scenario: Patient list for the UI picker", async () => {
    const config = configFromEnv({
      LLM_PROVIDER: "stub",
      PORT: "0",
      DATA_DIR: dataDir,
    });
    const server = await startAgentServer(config);
    close = server.close;

    const res = await fetch(`${server.baseUrl}/patients`);
    expect(res.status).toBe(200);
    const patients = (await res.json()) as Array<{
      id: string;
      displayName: string;
      summaryIds: string[];
    }>;
    expect(patients.length).toBeGreaterThan(0);
    for (const p of patients) {
      expect(p.id).toBeTruthy();
      expect(p.displayName).toBeTruthy();
      expect(p.summaryIds.length).toBeGreaterThan(0);
    }
    const multi = patients.find((p) => p.id === "multi_01");
    expect(multi?.summaryIds).toEqual(["strep_02", "uti_02"]);
  });

  it("Scenario: Health check", async () => {
    const config = configFromEnv({
      LLM_PROVIDER: "stub",
      PORT: "0",
      DATA_DIR: dataDir,
      AGENT_INSTANCE: "test-agent",
    });
    const server = await startAgentServer(config);
    close = server.close;

    const res = await fetch(`${server.baseUrl}/health`);
    expect(res.status).toBe(200);
    const body = (await res.json()) as {
      instanceId: string;
      llmProvider: string;
    };
    expect(body.instanceId).toBe("test-agent");
    expect(body.llmProvider).toBe("stub");
  });
});
